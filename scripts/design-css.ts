/**
 * Generates src/design/theme.css from src/design/themes/*.ts (`npm run design:css`).
 * `--check` exits 1 when the committed file is stale (CI).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { THEMES } from "../src/design/themes-registry";
import { FONT_VARS } from "../src/design/font-vars";
import { luminance, mix } from "../src/design/accent";
import { TYPE_ROLES, type ThemeDefinition, type TypeRole } from "../src/design/tokens";

const OUT = "src/design/theme.css";
const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function stack(def: ThemeDefinition, slot: "display" | "body" | "mono") {
  const v = FONT_VARS[def.families[slot]];
  return v ? `var(${v}), ${def.stacks[slot]}` : def.stacks[slot];
}

function block(def: ThemeDefinition): string {
  const t = def.tokens;
  const c = t.color;
  const dark = luminance(c.bg) < 0.18;
  const tint = (hex: string) => mix(c.bg, hex, dark ? 0.16 : 0.1);
  const lines: string[] = [];
  const v = (k: string, val: string | number) => lines.push(`  --${k}: ${val};`);
  for (const [k, val] of Object.entries(c)) v(kebab(k), val);
  v("positive-tint", tint(c.positive));
  v("negative-tint", tint(c.negative));
  v("warn-tint", tint(c.warn));
  v("font-display", stack(def, "display"));
  v("font-body", stack(def, "body"));
  v("font-mono", stack(def, "mono"));
  v("font-sans", "var(--font-body)");
  for (const role of TYPE_ROLES) {
    const s = t.type[role as TypeRole];
    const p = `type-${kebab(role)}`;
    v(`${p}-family`, `var(--font-${s.family})`);
    v(`${p}-size`, `${s.size}px`);
    v(`${p}-line`, `${s.line}px`);
    v(`${p}-tracking`, `${s.tracking}em`);
    v(`${p}-weight`, s.weight);
    v(`${p}-style`, s.italic ? "italic" : "normal");
    v(`${p}-case`, s.upper ? "uppercase" : "none");
  }
  for (const [k, val] of Object.entries(t.radius)) v(`radius-${kebab(k)}`, `${val}px`);
  v("border-hairline", `${t.border.hairline}px`);
  v("border-strong", `${t.border.strong}px`);
  v("space-page", `${t.space.page}px`);
  v("space-section", `${t.space.section}px`);
  v("shadow", t.shadow === "none" ? "0 0 #0000" : t.shadow);
  v("icon-stroke", def.variants.iconStroke);
  v("color-scheme", dark ? "dark" : "light");
  return lines.join("\n");
}

const utilities = TYPE_ROLES.filter((r) => r !== "h1Desktop")
  .map((role) => {
    const p = `type-${kebab(role)}`;
    return `.${p} {\n  font-family: var(--${p}-family);\n  font-size: var(--${p}-size);\n  line-height: var(--${p}-line);\n  letter-spacing: var(--${p}-tracking);\n  font-weight: var(--${p}-weight);\n  font-style: var(--${p}-style);\n  text-transform: var(--${p}-case);\n}`;
  })
  .join("\n");

const css = `/* GENERATED by \`npm run design:css\` from src/design/themes/*.ts. Do not edit by hand. */

${Object.values(THEMES)
  .map((def) => `${def.id === "maison" ? ":root,\n" : ""}[data-theme="${def.id}"] {\n${block(def)}\n  color-scheme: var(--color-scheme);\n}`)
  .join("\n\n")}

${utilities}
@media (min-width: 1024px) {
  .type-h1 {
    font-family: var(--type-h1-desktop-family);
    font-size: var(--type-h1-desktop-size);
    line-height: var(--type-h1-desktop-line);
    letter-spacing: var(--type-h1-desktop-tracking);
  }
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    /* missing */
  }
  if (current !== css) {
    console.error(`${OUT} is stale. Run \`npm run design:css\` and commit the result.`);
    process.exit(1);
  }
  console.log(`✓ ${OUT} is up to date`);
} else {
  writeFileSync(OUT, css);
  console.log(`Wrote ${OUT}`);
}
